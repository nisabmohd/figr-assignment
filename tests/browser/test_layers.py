from lib import *
async def cfof(page, title):
    h = await page.locator(f'iframe[title="{title}"]').element_handle()
    return await h.content_frame()
async def main():
    t=T()
    async with async_playwright() as p:
        b,page,logs = await start(p)
        await bring_exact(page,"scr-05",0.6)
        fb = await frame_box(page,"scr-05"); z = fb["width"]/1280
        cf = await cfof(page,"Settings tree")
        leaf = await cf.evaluate("""() => { let best=null,bd=-1; for (const el of document.querySelectorAll('.leaf')) { const r=el.getBoundingClientRect(); if (r.top<0||r.bottom>790||r.left>1270) continue; let d=0; for(let n=el;n!==document.body;n=n.parentElement) d++; if(d>bd){bd=d;best={x:r.left+r.width/2,y:r.top+r.height/2,d}} } return best; }""")
        print("deepest visible leaf", leaf)
        px, py = fb["x"]+leaf["x"]*z, fb["y"]+leaf["y"]*z
        await page.mouse.move(px,py); await page.wait_for_timeout(300)
        t.check("hover without an active preview highlights nothing and expands nothing", await page.locator(".row").count()==0)
        await page.mouse.click(px,py); await page.wait_for_timeout(800)
        sel = page.locator(".row.selected")
        t.check("selected row exists after deep select", await sel.count()==1)
        opened = await page.locator(".chev", has_text="▾").count()
        t.check(f"ancestors expanded ({opened})", opened>=leaf["d"]-3, opened)
        rb = await sel.bounding_box(); sc = await page.locator(".rows").bounding_box()
        t.check("panel scrolled to the row", rb is not None and rb["y"]>=sc["y"]-1 and rb["y"]+rb["height"]<=sc["y"]+sc["height"]+1, f"{rb} {sc}")
        n_rows = await page.locator(".rows .row").count()
        print("rows", n_rows)
        # collapse first row, hover the leaf again -> nearest visible ancestor row
        chev_texts = await page.locator(".rows .row .chev").all_inner_texts()
        first_chev = page.locator(".rows .row .chev").nth(chev_texts.index("▾"))
        await first_chev.click(); await page.wait_for_timeout(200)
        await page.mouse.move(px+3,py); await page.mouse.move(px,py); await page.wait_for_timeout(300)
        t.check("hover on collapsed subtree highlights an ancestor row", await page.locator(".row.hovered").count()==1)
        # expand again (loaded already -> no duplicates)
        await first_chev.click(); await page.wait_for_timeout(200)
        await first_chev.click(); await first_chev.click(); await page.wait_for_timeout(200)
        names = await page.locator(".rows .row .name").all_inner_texts()
        t.check("no duplicate rows after rapid toggles", len(page.locator(".rows .row").__class__.__name__) and len(names)==len(set(range(len(names)))))
        # row hover -> outline in preview
        row = page.locator(".rows .row").nth(1)
        await row.hover(); await page.wait_for_timeout(300)
        t.check("row hover draws outline in the page", await page.locator(".box.hover").count()==1)
        await page.mouse.move(120,70); await page.wait_for_timeout(200)
        t.check("leaving row clears hover", await page.locator(".box.hover").count()==0)
        # keyboard in panel
        await page.locator(".rows .row").first.click(); await page.wait_for_timeout(300)
        await page.locator(".rows").focus()
        await page.keyboard.press("ArrowRight"); await page.wait_for_timeout(400)
        n2 = await page.locator(".rows .row").count()
        await page.keyboard.press("ArrowDown"); await page.wait_for_timeout(300)
        t.check("ArrowDown moves selection", await page.locator(".row.selected .name").first.inner_text()!="")
        await page.keyboard.press("ArrowLeft"); await page.wait_for_timeout(300)
        sname = await page.locator(".row.selected").count()
        t.check("ArrowLeft moves to parent (collapsed child)", sname==1)
        # shift-click rows for multi-select
        await page.locator(".rows .row").nth(0).click()
        await page.locator(".rows .row").nth(1).click(modifiers=["Shift"]); await page.wait_for_timeout(300)
        t.check("shift+click row multi-selects", await page.locator(".row.selected").count()==2)
        t.check("inspector shows 2 elements", "2 elements" in await page.locator(".inspector").inner_text())
        t.check("inspector shows Mixed", "Mixed" in await page.locator(".inspector").inner_text())
        # search
        state_before = await page.locator(".rows .row").evaluate_all("els=>els.map(e=>e.innerText+'|'+e.style.paddingLeft)")
        await page.locator(".search").fill("Level 12"); await page.wait_for_timeout(600)
        found = await page.locator(".rows .row .name").all_inner_texts()
        t.check("search finds unloaded rows", any("Level 12" in n for n in found) , found[:5])
        before_open = n2
        await page.locator(".rows .row").nth(len(found)-1).click(); await page.wait_for_timeout(400)
        t.check("search stays open after selecting a result", await page.locator(".search").input_value()=="Level 12")
        await page.locator(".search").fill(""); await page.wait_for_timeout(400)
        state_after = await page.locator(".rows .row").evaluate_all("els=>els.map(e=>e.innerText+'|'+e.style.paddingLeft)")
        t.check("clearing search restores exactly the previous expanded state", state_before==state_after, f"{len(state_before)} vs {len(state_after)}")
        after = len(state_after)
        print("rows before search", n2, "after clear", after)
        # switch active preview and back: scroll restored
        await page.locator(".rows").evaluate("e=>e.scrollTop=300"); await page.wait_for_timeout(200)
        top_before = await page.locator(".rows").evaluate("e=>e.scrollTop")
        fb1 = await frame_box(page,"scr-01")
        print("reports", len(reports(logs)))
        
        print(f"\n{t.ok} ok, {t.bad} failed")
        await b.close()
asyncio.run(main())
